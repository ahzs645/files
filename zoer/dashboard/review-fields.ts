/**
 * Typed output fields for saved review prompts.
 *
 * The host stores only a prompt's name and text and accepts any `fields` object from the model,
 * so the field definitions travel inside the prompt text: the editor appends a generated output
 * contract (read by the model) ending in a machine-readable <review-fields> tag (read back here).
 * Changing a field therefore bumps the prompt version and invalidates reused results, like any edit.
 */

export const FIELD_TYPES = ['text', 'number', 'percent', 'scale', 'money', 'date', 'yes-no', 'choice', 'list'] as const;
export type FieldType = typeof FIELD_TYPES[number];
/** A whole-number rating range; the labels explain what the ends mean. */
export type Scale = { min: number; max: number; lowLabel?: string; highLabel?: string };
export type ReviewField = { key: string; label: string; type: FieldType; description: string; options?: string[]; scale?: Scale };
export const DEFAULT_SCALE: Scale = { min: 1, max: 5 };
const scaleOf = (field: ReviewField): Scale => field.scale ?? DEFAULT_SCALE;

export const MAX_FIELDS = 30;
export const MAX_PROMPT_LENGTH = 12000;

export const FIELD_TYPE_LABELS: Record<FieldType, string> = {
  text: 'Text', number: 'Number', percent: 'Percentage', scale: 'Scale (rating)', money: 'Money', date: 'Date', 'yes-no': 'Yes / no', choice: 'One of a list', list: 'List of items',
};
const FORMATS: Record<FieldType, string> = {
  text: 'a short string',
  number: 'a JSON number without units, commas or ranges',
  percent: 'a JSON number from 0 to 100 meaning percent (15 means 15%), without a % sign',
  scale: 'a whole number',
  money: '{"amount": number, "currency": "CAD"} using an ISO 4217 currency code',
  date: '"YYYY-MM-DD", or "YYYY-MM-DDTHH:MM" plus the stated UTC offset when a time is given',
  'yes-no': 'true or false',
  choice: 'exactly one of the listed options',
  list: 'an array of short strings, [] when the evidence shows there are none',
};
const EXAMPLES: Record<FieldType, unknown> = {
  text: 'Replace the arena roof membrane', number: 3, percent: 15, scale: 3, money: { amount: 250000, currency: 'CAD' }, date: '2026-10-15', 'yes-no': true, choice: '', list: ['COR certificate'],
};

const HEADER = 'OUTPUT FIELDS (generated by the prompt editor)';
const TAG = /<review-fields>([\s\S]*?)<\/review-fields>\s*$/;
const KEY = /^[a-z][A-Za-z0-9]{0,39}$/;
const DATE = /^\d{4}-(0[1-9]|1[0-2])-(0[1-9]|[12]\d|3[01])(T([01]\d|2[0-3]):[0-5]\d(:[0-5]\d)?(Z|[+-]\d{2}:\d{2})?)?$/;

/** camelCase key from a label, unique among `taken`. */
export function fieldKey(label: string, taken: string[] = []) {
  const words = label.normalize('NFKD').replace(/[^A-Za-z0-9 ]+/g, ' ').replace(/^[\s0-9]+/, '').trim().split(/\s+/).filter(Boolean);
  const base = words.map((w, i) => i ? w[0].toUpperCase() + w.slice(1).toLowerCase() : w.toLowerCase()).join('').slice(0, 36) || 'field';
  let key = base, n = 2;
  while (taken.includes(key)) key = `${base}${n++}`;
  return key;
}

/** Problems that would make the contract ambiguous; empty when the fields can be saved. */
export function fieldProblems(fields: ReviewField[]): string[] {
  const problems: string[] = [];
  if (fields.length > MAX_FIELDS) problems.push(`Use at most ${MAX_FIELDS} fields.`);
  const seen = new Set<string>();
  fields.forEach((f, index) => {
    const name = f.label.trim() || `Field ${index + 1}`;
    if (!f.label.trim()) problems.push(`${name}: add a name.`);
    if (!KEY.test(f.key)) problems.push(`${name}: the key must start with a lowercase letter and use only letters and digits.`);
    else if (seen.has(f.key)) problems.push(`${name}: the key "${f.key}" is used twice.`);
    seen.add(f.key);
    if (!f.description.trim()) problems.push(`${name}: describe what the AI should extract.`);
    const options = new Set((f.options ?? []).map(o => o.trim()).filter(Boolean));
    if (f.type === 'choice' && options.size < 2) problems.push(`${name}: list at least two different options.`);
    if (f.type === 'choice' && options.size > 20) problems.push(`${name}: use at most 20 options.`);
    if (f.type === 'scale') {
      const { min, max } = scaleOf(f);
      if (!Number.isInteger(min) || !Number.isInteger(max) || min >= max) problems.push(`${name}: the scale needs whole numbers with the lowest below the highest.`);
      else if (max - min > 100) problems.push(`${name}: keep the scale to at most 100 steps.`);
    }
  });
  return [...new Set(problems)];
}

const clean = (fields: ReviewField[]): ReviewField[] => fields.map(f => ({
  key: f.key, label: f.label.trim().slice(0, 60), type: f.type, description: f.description.trim().replace(/\s+/g, ' ').slice(0, 400),
  ...(f.type === 'choice' ? { options: [...new Set((f.options ?? []).map(o => o.trim().slice(0, 60)).filter(Boolean))].slice(0, 20) } : {}),
  ...(f.type === 'scale' ? { scale: cleanScale(scaleOf(f)) } : {}),
}));
const cleanScale = ({ min, max, lowLabel, highLabel }: Scale): Scale => ({
  min, max, ...(lowLabel?.trim() ? { lowLabel: lowLabel.trim().slice(0, 60) } : {}), ...(highLabel?.trim() ? { highLabel: highLabel.trim().slice(0, 60) } : {}),
});
/** "an integer from 1 to 5 (1 = poor fit, 5 = strong fit)" */
function scaleFormat({ min, max, lowLabel, highLabel }: Scale) {
  const ends = [lowLabel && `${min} = ${lowLabel}`, highLabel && `${max} = ${highLabel}`].filter(Boolean).join(', ');
  return `a whole number from ${min} to ${max}${ends ? ` (${ends})` : ''}`;
}

/** The instructions the model receives about `fields`; also shown in the editor preview. */
export function outputContract(fields: ReviewField[]): string {
  if (!fields.length) return '';
  const list = clean(fields);
  const lines = list.map(f => `- "${f.key}" (${f.label}; ${f.type === 'choice' ? `one of ${f.options!.map(o => JSON.stringify(o)).join(', ')}` : f.type === 'scale' ? scaleFormat(f.scale!) : FORMATS[f.type]}): ${f.description}`);
  const example = Object.fromEntries(list.map(f => [f.key, f.type === 'choice' ? f.options![0] : f.type === 'scale' ? Math.round((f.scale!.min + f.scale!.max) / 2) : EXAMPLES[f.type]]));
  return [
    HEADER,
    'Return "fields" as a JSON object with exactly these keys and no others. Use null when the reviewed evidence does not state a value; never guess, estimate or convert units. Cite evidence for every non-null value. Keep text values under 300 characters and lists under 12 items.',
    ...lines,
    'When combining earlier reviews, keep any non-null value found in a source and describe conflicting values in the summary.',
    `Shape example (values are illustrative only): ${JSON.stringify(example)}`,
    `<review-fields>${JSON.stringify({ v: 1, fields: list })}</review-fields>`,
  ].join('\n');
}

/** Saved prompt text: the operator's instructions followed by the generated contract. */
export function composePrompt(instructions: string, fields: ReviewField[]) {
  const contract = outputContract(fields);
  return contract ? `${instructions.trimEnd()}\n\n${contract}` : instructions;
}

/** Split saved prompt text back into editable instructions and typed fields. */
export function parsePrompt(text: string | undefined | null): { instructions: string; fields: ReviewField[] } {
  const value = text ?? '', at = value.lastIndexOf(HEADER);
  if (at < 0) return { instructions: value, fields: [] };
  const instructions = value.slice(0, at).trimEnd();
  try {
    const parsed = JSON.parse(TAG.exec(value.slice(at))?.[1] ?? '');
    const fields = (Array.isArray(parsed?.fields) ? parsed.fields : []).filter((f: any) => f && typeof f.key === 'string' && FIELD_TYPES.includes(f.type))
      .map((f: any) => ({ key: f.key, label: String(f.label ?? f.key), type: f.type, description: String(f.description ?? ''), ...(Array.isArray(f.options) ? { options: f.options.map(String) } : {}),
        ...(f.scale && typeof f.scale === 'object' ? { scale: { min: Number(f.scale.min), max: Number(f.scale.max), ...(typeof f.scale.lowLabel === 'string' ? { lowLabel: f.scale.lowLabel } : {}), ...(typeof f.scale.highLabel === 'string' ? { highLabel: f.scale.highLabel } : {}) } } : {}) }));
    return { instructions, fields };
  } catch { return { instructions, fields: [] }; }
}

/** A returned value by key, ignoring inherited properties such as `constructor`. */
export const fieldValue = (output: unknown, key: string) =>
  output && typeof output === 'object' && !Array.isArray(output) && Object.prototype.hasOwnProperty.call(output, key) ? (output as Record<string, unknown>)[key] : undefined;

export type FieldCheck = { field: ReviewField; value: unknown; state: 'ok' | 'empty' | 'missing' | 'invalid'; note?: string };

function invalid(field: ReviewField, value: unknown): string | undefined {
  switch (field.type) {
    case 'text': return typeof value === 'string' ? undefined : 'Expected text.';
    case 'number': return typeof value === 'number' && Number.isFinite(value) ? undefined : 'Expected a number.';
    case 'percent': return typeof value === 'number' && value >= 0 && value <= 100 ? undefined : 'Expected a number from 0 to 100.';
    case 'scale': { const { min, max } = scaleOf(field); return Number.isInteger(value) && (value as number) >= min && (value as number) <= max ? undefined : `Expected a whole number from ${min} to ${max}.`; }
    case 'yes-no': return typeof value === 'boolean' ? undefined : 'Expected true or false.';
    case 'date': return typeof value === 'string' && DATE.test(value) ? undefined : 'Expected YYYY-MM-DD.';
    case 'choice': return field.options?.includes(value as string) ? undefined : `Expected one of: ${field.options?.join(', ')}.`;
    case 'list': return Array.isArray(value) && value.every(item => typeof item === 'string') ? undefined : 'Expected a list of text items.';
    case 'money': {
      const m = value as any;
      return m && typeof m === 'object' && typeof m.amount === 'number' && Number.isFinite(m.amount) && typeof m.currency === 'string' && /^[A-Z]{3}$/.test(m.currency) ? undefined : 'Expected {amount, currency}.';
    }
  }
}

/** Compare a review's `fields` with the prompt's definitions. */
export function checkFields(fields: ReviewField[], output: unknown) {
  const values = output && typeof output === 'object' && !Array.isArray(output) ? output as Record<string, unknown> : {};
  const checks: FieldCheck[] = fields.map(field => {
    if (!Object.prototype.hasOwnProperty.call(values, field.key)) return { field, value: undefined, state: 'missing', note: 'Not returned.' };
    const value = values[field.key];
    if (value === null || value === '') return { field, value, state: 'empty' };
    const note = invalid(field, value);
    return { field, value, state: note ? 'invalid' : 'ok', note };
  });
  const extra = Object.keys(values).filter(key => !fields.some(f => f.key === key));
  return { checks, extra, problems: checks.filter(c => c.state === 'missing' || c.state === 'invalid').length };
}

/** Display text for a typed value; falls back to raw JSON when the value does not match its type. */
export function formatTyped(field: ReviewField, value: unknown): string | string[] {
  if (value === undefined) return 'Not returned';
  if (value === null || value === '') return 'Not stated';
  if (invalid(field, value)) return typeof value === 'string' ? value : JSON.stringify(value);
  switch (field.type) {
    case 'money': { const m = value as { amount: number; currency: string }; return new Intl.NumberFormat(undefined, { style: 'currency', currency: m.currency, maximumFractionDigits: 0 }).format(m.amount); }
    case 'number': return (value as number).toLocaleString();
    case 'percent': return `${(value as number).toLocaleString(undefined, { maximumFractionDigits: 2 })}%`;
    case 'scale': return `${value} / ${scaleOf(field).max}`;
    case 'yes-no': return value ? 'Yes' : 'No';
    case 'list': return (value as string[]).length ? value as string[] : 'None';
    default: return String(value);
  }
}

/** Starting field definitions guessed from an earlier free-form result, for converting legacy prompts. */
export function suggestFields(sample: unknown): ReviewField[] {
  if (!sample || typeof sample !== 'object' || Array.isArray(sample)) return [];
  const taken: string[] = [];
  return Object.entries(sample as Record<string, unknown>).slice(0, MAX_FIELDS).map(([name, value]) => {
    const label = name.replace(/([a-z])([A-Z])/g, '$1 $2').replace(/[_-]+/g, ' ').replace(/^./, c => c.toUpperCase());
    const key = KEY.test(name) && !taken.includes(name) ? name : fieldKey(label, taken);
    taken.push(key);
    const type: FieldType = typeof value === 'number' ? 'number' : typeof value === 'boolean' ? 'yes-no' : Array.isArray(value) ? 'list'
      : value && typeof value === 'object' && 'amount' in value ? 'money' : typeof value === 'string' && DATE.test(value) ? 'date' : 'text';
    return { key, label, type, description: `${label} as stated in the evidence.` };
  });
}

